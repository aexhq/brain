// Command generate derives wire declarations and OpenAPI from Go types/routes.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"reflect"
	"sort"
	"strconv"
	"strings"
	"time"

	"github.com/aexhq/brain/internal/api"
	"github.com/aexhq/brain/internal/core"
	"github.com/aexhq/brain/internal/harness"
)

var names = map[reflect.Type]string{
	reflect.TypeFor[core.Config]():     "SessionConfig",
	reflect.TypeFor[core.Error]():      "ErrorDetail",
	reflect.TypeFor[harness.Options](): "OpenOptions",
}
var schemas = map[string]any{}
var declarations = map[string]string{}
var python = map[string]string{}

func visit(t reflect.Type) (string, string, map[string]any) {
	if t == reflect.TypeFor[json.RawMessage]() {
		return "unknown", "Any", map[string]any{}
	}
	if t == reflect.TypeFor[time.Time]() {
		return "string", "str", map[string]any{"type": "string", "format": "date-time"}
	}
	if t.Kind() == reflect.Pointer {
		return visit(t.Elem())
	}
	switch t.Kind() {
	case reflect.String:
		return "string", "str", map[string]any{"type": "string"}
	case reflect.Bool:
		return "boolean", "bool", map[string]any{"type": "boolean"}
	case reflect.Int, reflect.Int64, reflect.Int32, reflect.Uint64:
		return "number", "int", map[string]any{"type": "integer"}
	case reflect.Slice:
		ts, py, s := visit(t.Elem())
		return ts + "[]", "list[" + py + "]", map[string]any{"type": "array", "items": s}
	case reflect.Struct:
		name := names[t]
		if name == "" {
			name = t.Name()
		}
		if name == "" {
			panic("unnamed wire struct")
		}
		if _, ok := schemas[name]; !ok {
			schemas[name] = nil
			var ts, py strings.Builder
			fmt.Fprintf(&ts, "export interface %s {\n", name)
			fmt.Fprintf(&py, "class %s(TypedDict):\n", name)
			props := map[string]any{}
			required := []string{}
			for i := 0; i < t.NumField(); i++ {
				f := t.Field(i)
				tag := f.Tag.Get("json")
				field, options, _ := strings.Cut(tag, ",")
				if field == "-" || f.Tag.Get("wire") == "-" {
					continue
				}
				if field == "" {
					panic("wire field requires json tag: " + f.Name)
				}
				ft, fp, fs := visit(f.Type)
				props[field] = fs
				optional := strings.Contains(options, "omitempty")
				marker := ""
				if optional {
					marker = "?"
					fp = "NotRequired[" + fp + "]"
				} else {
					required = append(required, field)
				}
				fmt.Fprintf(&ts, "  %s%s: %s;\n", field, marker, ft)
				fmt.Fprintf(&py, "    %s: %s\n", field, fp)
			}
			ts.WriteString("}\n")
			schemas[name] = map[string]any{"type": "object", "properties": props, "required": required, "additionalProperties": false}
			declarations[name] = ts.String()
			python[name] = py.String()
		}
		return name, name, map[string]any{"$ref": "#/components/schemas/" + name}
	default:
		panic("unsupported wire type: " + t.String())
	}
}

func main() {
	check := flag.Bool("check", false, "fail if generated files differ")
	flag.Parse()
	for _, route := range api.Contract() {
		if route.Input != nil {
			visit(route.Input)
		}
		visit(route.Output)
	}
	visit(reflect.TypeFor[api.ErrorResponse]())
	visit(reflect.TypeFor[core.SyncStatus]())
	visit(reflect.TypeFor[core.ModelRequest]())
	for _, t := range []reflect.Type{reflect.TypeFor[core.CreateSession](), reflect.TypeFor[core.Session](), reflect.TypeFor[core.Input](), reflect.TypeFor[core.Event](), reflect.TypeFor[core.Tool](), reflect.TypeFor[core.Call](), reflect.TypeFor[core.Result](), reflect.TypeFor[core.ToolResult](), reflect.TypeFor[core.Error]()} {
		visit(t)
	}
	keys := make([]string, 0, len(declarations))
	for key := range declarations {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	var ts, py strings.Builder
	ts.WriteString("// Generated by go run ./cmd/generate; do not edit.\n\n")
	py.WriteString("# Generated by go run ./cmd/generate; do not edit.\nfrom __future__ import annotations\nfrom typing import Any, NotRequired, TypedDict\n\n")
	for _, key := range keys {
		ts.WriteString(declarations[key] + "\n")
		py.WriteString(python[key] + "\n")
	}
	paths := map[string]any{}
	routeValues := map[string]any{}
	for _, route := range api.Contract() {
		routeValues[route.Name] = map[string]string{"method": route.Method, "path": route.Path}
		_, _, output := visit(route.Output)
		if route.Name == "send" {
			_, _, status := visit(reflect.TypeFor[core.Status]())
			output = map[string]any{"oneOf": []any{output, status}}
		}
		content := map[string]any{"application/json": map[string]any{"schema": output}}
		if route.Name == "events" {
			content["text/event-stream"] = map[string]any{"schema": map[string]any{"type": "string"}, "example": "id: OPAQUE_CURSOR\nevent: assistant.message\ndata: {\"id\":\"EVENT_ID\",\"type\":\"assistant.message\",\"time\":\"2026-10-15T12:00:00Z\",\"input_id\":\"INPUT_ID\",\"data\":{\"text\":\"Hello\"},\"cursor\":\"OPAQUE_CURSOR\"}\n\n"}
		}
		if route.Name == "executorCommands" {
			content = map[string]any{"text/event-stream": map[string]any{"schema": map[string]any{"type": "string"}, "example": "data: {\"type\":\"ready\",\"connection\":\"CONNECTION_ID\"}\n\n"}}
		}
		if route.Name == "executorRPC" {
			content = map[string]any{}
		}
		_, _, errorSchema := visit(reflect.TypeFor[api.ErrorResponse]())
		responses := map[string]any{
			strconv.Itoa(route.Status): map[string]any{"description": route.Summary, "content": content},
			"default":                  map[string]any{"description": "Error. 400 invalid_request; 401 missing/invalid Bearer token; 403 forbidden; 404 not_found; 409 conflict or cursor_unavailable; 413 body limit; 422 unsupported; 429 overloaded (Retry-After: 1); 500 brain_error. X-Request-ID is present on every response.", "content": map[string]any{"application/json": map[string]any{"schema": errorSchema}}},
		}
		op := map[string]any{"operationId": route.Name, "summary": route.Summary, "description": route.Description, "security": []any{map[string]any{"bearer": []string{}}}, "responses": responses}
		parameters := []any{}
		if strings.Contains(route.Path, "{id}") {
			description := "Opaque session ID."
			if strings.HasPrefix(route.Path, "/executors/") {
				description = "Opaque executor ID."
			}
			parameters = append(parameters, map[string]any{"name": "id", "in": "path", "description": description, "required": true, "schema": map[string]string{"type": "string", "pattern": "^[a-fA-F0-9]{32}$"}})
		}
		if route.Name == "list" || route.Name == "events" {
			afterDescription := "Last session ID from the previous page."
			if route.Name == "events" {
				afterDescription = "Opaque cursor from the last retained event."
			}
			parameters = append(parameters,
				map[string]any{"name": "after", "in": "query", "description": afterDescription, "schema": map[string]any{"type": "string"}},
				map[string]any{"name": "limit", "in": "query", "description": "Maximum number of items to return (JSON mode).", "schema": map[string]any{"type": "integer", "default": 100, "minimum": 1, "maximum": 1000}},
			)
		}
		if route.Name == "events" {
			parameters = append(parameters, map[string]any{"name": "Last-Event-ID", "in": "header", "description": "SSE reconnect cursor (used when the after query parameter is omitted).", "schema": map[string]any{"type": "string"}})
		}
		if len(parameters) != 0 {
			op["parameters"] = parameters
		}
		if route.Input != nil {
			_, _, schema := visit(route.Input)
			op["requestBody"] = map[string]any{"required": true, "content": map[string]any{"application/json": map[string]any{"schema": schema}}}
		}
		if paths[route.Path] == nil {
			paths[route.Path] = map[string]any{}
		}
		paths[route.Path].(map[string]any)[strings.ToLower(route.Method)] = op
	}
	routes, _ := json.MarshalIndent(routeValues, "", "  ")
	fmt.Fprintf(&ts, "export const routes = %s as const;\n", routes)
	apiDoc := map[string]any{"openapi": "3.1.0", "info": map[string]string{"title": "Brain", "version": "current", "description": "HTTP API for the Brain agent session server."}, "servers": []any{map[string]string{"url": "http://127.0.0.1:8080", "description": "Local development"}}, "paths": paths, "components": map[string]any{"schemas": schemas, "securitySchemes": map[string]any{"bearer": map[string]string{"type": "http", "scheme": "bearer"}}}}
	doc, _ := json.MarshalIndent(apiDoc, "", "  ")
	visit(reflect.TypeFor[harness.Options]())
	visit(reflect.TypeFor[harness.RunnerFrame]())
	visit(reflect.TypeFor[core.NativeFile]())
	keys = nil
	for key := range declarations {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	var wire strings.Builder
	wire.WriteString("// Generated by go run ./cmd/generate; do not edit.\n\n")
	for _, key := range keys {
		wire.WriteString(declarations[key] + "\n")
	}
	files := map[string][]byte{"api/openapi.json": append(doc, '\n'), "sdks/typescript/src/generated.ts": []byte(ts.String()), "runners/pi/src/generated.ts": []byte(wire.String()), "sdks/python/brain/types.py": []byte(py.String())}
	failed := false
	for file, data := range files {
		if *check {
			old, err := os.ReadFile(file)
			if err != nil || !bytes.Equal(old, data) {
				fmt.Fprintln(os.Stderr, "generated file differs:", file)
				failed = true
			}
		} else {
			if err := os.MkdirAll(filepath.Dir(file), 0755); err != nil {
				panic(err)
			}
			if err := os.WriteFile(file, data, 0644); err != nil {
				panic(err)
			}
		}
	}
	if failed {
		os.Exit(1)
	}
}
