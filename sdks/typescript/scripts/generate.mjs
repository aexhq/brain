import { readFile, writeFile } from 'node:fs/promises';
import openapiTS, { astToString } from 'openapi-typescript';

const root = new URL('../../../', import.meta.url);
const check = process.argv.includes('--check');
for (const [source, target, http] of [
  ['services/brain/api/openapi.json', 'sdks/typescript/src/generated.ts', true],
  ['runtimes/host/protocol.json', 'runtimes/pi/src/generated.ts', false],
]) {
  const schema = JSON.parse(await readFile(new URL(source, root), 'utf8'));
  let output = '// Generated by node sdks/typescript/scripts/generate.mjs; do not edit.\n\n';
  output += astToString(await openapiTS(schema, { alphabetize: true }));
  // Public names are aliases of library-generated component types, not a
  // second schema-to-language implementation.
  for (const name of Object.keys(schema.components.schemas).sort()) {
    output += `\nexport type ${name} = components["schemas"]["${name}"];\n`;
  }
  if (http) {
    const routes = Object.fromEntries(Object.entries(schema.paths).flatMap(([path, methods]) =>
      Object.entries(methods).map(([method, op]) => [op.operationId, { method: method.toUpperCase(), path }])));
    output += `\nexport const routes = ${JSON.stringify(routes, null, 2)} as const;\n`;
  }
  const file = new URL(target, root);
  if (check) {
    if (await readFile(file, 'utf8') !== output) throw new Error(`Generated file differs: ${target}`);
  } else await writeFile(file, output);
}
